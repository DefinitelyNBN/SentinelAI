"""Paderborn Bearing Dataset loader for PyTorch.

Phase 5 — Dataset Generation.

This module replaces the generic ManifestSignalDataset (src/dataset.py) for
the Paderborn experiment.  It:

  - Reads the manifest CSV generated by src/generate_manifest.py.
  - Loads each window on-the-fly from the source MAT file.
  - Applies training-only Z-score normalisation.
  - Applies optional (disabled by default) augmentations.
  - Returns (x, label_id) where x has shape (1, 64000).

Design decisions
----------------
*  No .npy cache files:   Windows are sliced from MAT files at __getitem__
   time.  For a dataset of ~3 840 windows this is fast enough on any hardware.
   If profiling shows a bottleneck, a separate caching step can be added later.

*  Normalisation:         The caller MUST supply mean and std derived exclusively
   from the training split.  The loader does NOT compute these itself to prevent
   any accidental leakage.  Use
       paderborn_training_stats(train_dataset)
   to compute them from the training Dataset before constructing val/test sets.

*  Determinism:           __getitem__ is deterministic (given the same augment
   parameters) when called with the same index and the same seed.

*  Compatibility:         The (x, label_id) return type is identical to the
   existing ManifestSignalDataset, so SentinelAI / experiments.py / train.py
   require no changes.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Optional, Tuple

import numpy as np
import torch
from torch.utils.data import Dataset

from src.paderborn_mat import get_window_data


def validate_bearing_disjoint_manifest(manifest_path: str | Path) -> dict:
    """Fail fast if a bearing appears in more than one split.

    This is called by every dataset factory, rather than only by manifest
    generation scripts, so an edited/corrupted manifest cannot silently leak.
    """
    with open(manifest_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    required = {"split", "bearing_id", "label", "label_id"}
    if not rows or not required.issubset(rows[0]):
        raise ValueError(f"Manifest must contain {sorted(required)}")
    by_split = {s: [r for r in rows if r["split"] == s] for s in ("train", "validation", "test")}
    sets = {s: {r["bearing_id"] for r in group} for s, group in by_split.items()}
    overlaps = {"train_validation": sets["train"] & sets["validation"], "train_test": sets["train"] & sets["test"], "validation_test": sets["validation"] & sets["test"]}
    leaked = {name: sorted(values) for name, values in overlaps.items() if values}
    if leaked:
        raise ValueError(f"Bearing-disjoint split violation: {leaked}")
    labels = {r["label"]: int(r["label_id"]) for r in rows}
    expected = {"healthy": 0, "outer_ring": 1, "inner_ring": 2}
    if labels != expected:
        raise ValueError(f"Unexpected label mapping {labels}; expected {expected}.")
    return {s: {"bearings": sorted(sets[s]), "windows": len(by_split[s]), "windows_by_class": {label: sum(r["label"] == label for r in by_split[s]) for label in expected}} for s in by_split}


class PaderbornDataset(Dataset):
    """PyTorch Dataset for the Paderborn Bearing Benchmark.

    Parameters
    ----------
    manifest_path : str or Path
        Path to ``data/metadata/paderborn_manifest.csv``.
    split : str
        One of ``"train"``, ``"validation"``, ``"test"``.
    project_root : str or Path
        Project root; MAT paths in the manifest are relative to this.
    mean : float or None
        Training-set mean for Z-score normalisation.
        **Must be None for the raw training Dataset used to compute stats.**
    std : float or None
        Training-set std for Z-score normalisation (same constraint).
    augment : bool
        If True, applies the approved augmentations (disabled by default).
    aug_config : dict or None
        Augmentation hyper-parameters (read from config["training"]["augmentation"]).
    window_samples : int
        Window length in samples.  Must match the manifest (default 64 000).
    """

    LABEL_ORDER = ["healthy", "outer_ring", "inner_ring"]  # sorted alphabetically

    def __init__(
        self,
        manifest_path: str | Path,
        split: str,
        project_root: str | Path = ".",
        mean: Optional[float] = None,
        std: Optional[float] = None,
        augment: bool = False,
        aug_config: Optional[dict] = None,
        window_samples: int = 64_000,
    ) -> None:
        self.manifest_path = Path(manifest_path)
        self.split = split
        self.project_root = Path(project_root).resolve()
        self.mean = mean
        self.std = std
        self.augment = augment
        self.aug_config = aug_config or {}
        self.window_samples = window_samples

        if not self.manifest_path.exists():
            raise FileNotFoundError(
                f"Manifest not found: {self.manifest_path}\n"
                "Run `python -m src.generate_manifest` to generate it."
            )

        self.rows = self._load_split(self.manifest_path, split)
        if not self.rows:
            raise ValueError(
                f"No rows found for split='{split}' in {self.manifest_path}."
            )

        # Build a label-to-id map from the manifest (alphabetically sorted = Phase 4 order).
        all_labels = sorted({r["label"] for r in self.rows})
        self.label_to_id = {lbl: i for i, lbl in enumerate(all_labels)}

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _load_split(manifest_path: Path, split: str) -> list[dict]:
        with open(manifest_path, newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            return [row for row in reader if row["split"] == split]

    def _mat_abspath(self, rel_mat_path: str) -> Path:
        return self.project_root / rel_mat_path

    # ------------------------------------------------------------------
    # PyTorch Dataset interface
    # ------------------------------------------------------------------

    def __len__(self) -> int:
        return len(self.rows)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int]:
        row = self.rows[idx]
        mat_path = self._mat_abspath(row["mat_path"])
        start = int(row["start_sample"])
        end = int(row["end_sample"])

        # 1. Load raw window (float32, shape (window_samples,))
        x: np.ndarray = get_window_data(mat_path, start, end)

        # 2. Augmentation (disabled unless augment=True)
        if self.augment:
            x = self._apply_augmentation(x)

        # 3. Normalisation. Dataset defaults are preserved (z-score, no filter).
        # Filtering is applied only when explicitly requested through aug_config
        # as the factory keeps default runs scientifically identical.
        if self.mean is not None and self.std is not None:
            x = (x - self.mean) / max(self.std, 1e-8)

        # 4. Convert to tensor, add channel dim → (1, window_samples)
        t = torch.from_numpy(x).unsqueeze(0)

        label_id = int(row["label_id"])
        return t, label_id

    # ------------------------------------------------------------------
    # Augmentation (Phase 4 approved; disabled for baseline)
    # ------------------------------------------------------------------

    def _apply_augmentation(self, x: np.ndarray) -> np.ndarray:
        """Apply only physically defensible vibration augmentations."""
        cfg = self.aug_config
        # Amplitude jitter: uniform scaling ∈ [1-scale, 1+scale]
        scale = float(cfg.get("amplitude_scale", 0.0))
        if scale > 0.0:
            x = x * np.random.uniform(1.0 - scale, 1.0 + scale)
        # Additive Gaussian noise
        noise_std = float(cfg.get("gaussian_noise_std", 0.0))
        if noise_std > 0.0:
            x = x + np.random.normal(0.0, noise_std, x.shape).astype(np.float32)
        return x

    # ------------------------------------------------------------------
    # Metadata helpers
    # ------------------------------------------------------------------

    def bearing_ids(self) -> list[str]:
        return sorted({r["bearing_id"] for r in self.rows})

    def class_counts(self) -> dict[str, int]:
        from collections import Counter
        return dict(Counter(r["label"] for r in self.rows))


# ---------------------------------------------------------------------------
# Training statistics (training-only normalisation)
# ---------------------------------------------------------------------------

def paderborn_training_stats(
    train_dataset: PaderbornDataset,
) -> Tuple[float, float]:
    """Compute global Z-score mean and std over ALL training windows.

    This function MUST be called on the training Dataset (split='train') only,
    before constructing validation or test datasets.

    Returns (mean, std) as Python floats.
    """
    if train_dataset.split != "train":
        raise ValueError(
            f"paderborn_training_stats() must be called with split='train', "
            f"got split='{train_dataset.split}'."
        )

    # Welford's online algorithm for numerical stability.
    n = 0
    mean_acc = 0.0
    M2 = 0.0

    for row in train_dataset.rows:
        mat_path = train_dataset._mat_abspath(row["mat_path"])
        x = get_window_data(mat_path, int(row["start_sample"]), int(row["end_sample"]))
        for val in x.astype(np.float64):
            n += 1
            delta = val - mean_acc
            mean_acc += delta / n
            M2 += delta * (val - mean_acc)

    if n < 2:
        raise ValueError("Fewer than 2 training samples found.")

    std = float(np.sqrt(M2 / (n - 1)))
    return float(mean_acc), std


# ---------------------------------------------------------------------------
# Convenience factory — mirrors the API used by experiments.py
# ---------------------------------------------------------------------------

def build_datasets(
    cfg: dict,
    norm_stats_path: str | Path | None = None,
    include_test: bool = True,
) -> Tuple["PaderbornDataset", "PaderbornDataset", "PaderbornDataset | None", float, float]:
    """Build train / validation / test PaderbornDataset objects.

    Loads normalisation statistics from ``data/metadata/paderborn_norm_stats.json``
    (written by generate_manifest.py) to avoid recomputing them on every run.

    Returns (train_ds, val_ds, test_ds, mean, std).
    """
    d = cfg["dataset"]
    manifest = d.get("manifest") or "data/metadata/paderborn_manifest.csv"
    project_root = d.get("root", ".") if d.get("root") not in (None, "data") else "."

    # Enforce bearing-level split integrity before touching any window data.
    validate_bearing_disjoint_manifest(manifest)

    # A filtered signal needs filtered training-only statistics. Refuse a
    # common leakage/mismatch error instead of silently using raw statistics.
    pre = cfg.get("preprocessing", {})
    if pre.get("filter_enabled", False):
        raise ValueError(
            "Filtering is enabled but stored normalization statistics are raw. "
            "Regenerate training-only filtered stats before training/evaluation."
        )
    if norm_stats_path is None:
        norm_stats_path = Path("data/metadata/paderborn_norm_stats.json")

    if Path(norm_stats_path).exists():
        with open(norm_stats_path) as f:
            ns = json.load(f)
        mean, std = float(ns["mean"]), float(ns["std"])
    else:
        # Compute from training data (slower but safe).
        raw_train = PaderbornDataset(manifest, "train", project_root=project_root)
        mean, std = paderborn_training_stats(raw_train)

    normalization_method = pre.get("normalization_method", "zscore").lower()
    if normalization_method == "zscore":
        applied_mean, applied_std = mean, std
    elif normalization_method == "none":
        applied_mean = applied_std = None
    else:
        raise ValueError(
            f"Unsupported training normalization_method {normalization_method!r}. "
            "Use 'zscore' or 'none'; minmax requires recorded training extrema."
        )

    aug_cfg = cfg.get("training", {}).get("augmentation", {})

    train_ds = PaderbornDataset(
        manifest, "train", project_root=project_root,
        mean=applied_mean, std=applied_std, augment=True, aug_config=aug_cfg,
    )
    val_ds = PaderbornDataset(
        manifest, "validation", project_root=project_root,
        mean=applied_mean, std=applied_std, augment=False,
    )
    test_ds = None
    if include_test:
        test_ds = PaderbornDataset(manifest, "test", project_root=project_root, mean=applied_mean, std=applied_std, augment=False)

    return train_ds, val_ds, test_ds, mean, std
